/**
 * Uploaded icon paths are stored relative (`/uploads/icons/<uuid>.png`) so one
 * database value works in every environment. The backend mounts `/uploads` at
 * its root, outside the `/api` prefix that every API URL carries, so a relative
 * path must be resolved against the backend origin — otherwise the browser
 * requests it from this app's origin and gets a 404, and the icon silently
 * disappears.
 *
 * Only the public origin is used here, unlike the `fetch` calls in
 * `services/api.ts` which may target `INTERNAL_API_URL`. An `<img src>` is
 * rendered during SSR and shipped to the browser as-is, so the Docker-internal
 * `http://backend:4000` hostname would be embedded in the HTML and the browser
 * could not resolve it. This value ends up in client-visible HTML and must
 * always be reachable from the browser.
 */
const PUBLIC_API_URL = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:4000/api';

/**
 * Turns a stored `iconUrl` into a URL the browser can actually load.
 * Returns null for anything not renderable, so callers can fall back to the
 * built-in icon set rather than emitting an `<img>` with a broken src.
 */
export function resolveIconUrl(iconUrl: string | null | undefined): string | null {
  if (!iconUrl) return null;
  // Absolute URLs were already validated by the API; pass them through as-is.
  if (/^https?:\/\//i.test(iconUrl)) return iconUrl;
  if (!iconUrl.startsWith('/uploads/')) return null;
  return `${PUBLIC_API_URL.replace(/\/api\/?$/, '')}${iconUrl}`;
}

export function isCategoryIconKey(value: string | null | undefined): value is CategoryIconKey {
  return !!value && (CATEGORY_ICON_KEYS as readonly string[]).includes(value);
}

/** Inline SVG for a built-in key. Renders nothing when the key is unknown. */
export function CategoryIconSvg({ iconKey, className = 'h-4 w-4' }: { iconKey: string | null | undefined; className?: string }) {
  if (!isCategoryIconKey(iconKey)) return null;
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {PATHS[iconKey].map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  );
}

/**
 * Renders a category's icon, preferring an uploaded image over the built-in
 * set. Returns null when the category has neither, so callers can lay out
 * without reserving space.
 *
 * `mono` renders the icon as a solid silhouette in the inherited text colour
 * and is meant for dark surfaces. Built-in keys already use `stroke="currentColor"`
 * so they follow the text colour for free; uploaded PNGs are rasterised from
 * whatever colour the author's SVG happened to use (commonly black), which is
 * invisible on a dark header. Masking the image and filling it with
 * `currentColor` discards the PNG's own pixels, so uploaded and built-in icons
 * always match the label and pick up hover states.
 *
 * Leave `mono` off on light surfaces — a white icon on a white dropdown would
 * disappear.
 */
export function CategoryIcon({
  iconUrl,
  iconKey,
  className = 'h-4 w-4',
  alt = '',
  mono = false,
}: {
  iconUrl?: string | null;
  iconKey?: string | null;
  className?: string;
  alt?: string;
  mono?: boolean;
}) {
  const src = resolveIconUrl(iconUrl);
  if (src && mono) {
    return (
      <span
        role={alt ? 'img' : undefined}
        aria-label={alt || undefined}
        aria-hidden={alt ? undefined : true}
        className={`${className} inline-block shrink-0 bg-current`}
        style={{
          WebkitMaskImage: `url("${src}")`,
          maskImage: `url("${src}")`,
          WebkitMaskSize: 'contain',
          maskSize: 'contain',
          WebkitMaskRepeat: 'no-repeat',
          maskRepeat: 'no-repeat',
          WebkitMaskPosition: 'center',
          maskPosition: 'center',
        }}
      />
    );
  }
  if (src) {
    return (
      // Uploaded icons are always rasterized to PNG by the API, so a plain
      // <img> is safe here and needs no next/image configuration.
      <img
        src={src}
        alt={alt}
        aria-hidden={alt ? undefined : true}
        className={`${className} shrink-0 object-contain`}
        loading="lazy"
      />
    );
  }
  return <CategoryIconSvg iconKey={iconKey} className={className} />;
}

/** True when the category has an icon in either form. */
export function hasCategoryIcon(cat: { iconUrl?: string | null; iconKey?: string | null }): boolean {
  return !!resolveIconUrl(cat.iconUrl) || isCategoryIconKey(cat.iconKey);
}